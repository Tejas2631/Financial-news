def build():
    companies, tickers, seen = {}, {}, set()
    for name, aliases, ticker in _ROWS:
        assert name not in seen, f"duplicate company: {name}"
        seen.add(name)
        al = list(aliases)
        short_caps = name.isupper() and len(name) <= 5      # TCS, ITC, SAIL...: only the explicit "=TICKER" form
        if name not in NO_AUTO and not short_caps and name.lower() not in [a.lower() for a in al]:
            al.insert(0, name.lower())
        companies[name] = al
        if ticker:
            tickers[name] = ticker
    return companies, tickers


COMPANIES, TICKERS = build()
